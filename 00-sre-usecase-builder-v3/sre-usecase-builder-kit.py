def _fmt(value):
    if value is None:
        return "n/d"
    if isinstance(value, bool):
        return str(value)
    if isinstance(value, (int, float)):
        text = f"{value:,.0f}" if float(value).is_integer() else f"{value:,.2f}"
        return text.replace(",", "\u202f") if CONFIG.get("language", "es") == "es" else text
    return str(value)


def _e(value):
    return html.escape(_fmt(value))


