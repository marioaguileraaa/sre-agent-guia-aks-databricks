# @block publish:sharepoint
def _sp_put(site, path, content, ctype):
    target = f"{GRAPH}/v1.0/sites/{site}/drive/root:/{quote(path.strip('/'))}:"
    if len(content) <= 4_000_000:
        return _http("PUT", target + "/content", GRAPH_SCOPE, data=content, headers={"Content-Type": ctype}, ok=(200, 201)).json().get("webUrl")
    upload = _http("POST", target + "/createUploadSession", GRAPH_SCOPE, ok=(200,),
                   json_body={"item": {"@microsoft.graph.conflictBehavior": "replace"}}).json()["uploadUrl"]
    chunk, resp = 320 * 1024 * 10, None
    for start in range(0, len(content), chunk):
        part = content[start:start + chunk]
        resp = requests.put(upload, data=part, timeout=120,
                            headers={"Content-Range": f"bytes {start}-{start + len(part) - 1}/{len(content)}"})
        if resp.status_code not in (200, 201, 202):
            raise SourceError("UPLOAD_FAILED", f"SharePoint upload session -> HTTP {resp.status_code}", resp.status_code)
    return resp.json().get("webUrl") if resp is not None else None
# @endblock


# @block publish:blob
def _blob_put(account, container, name, content, ctype):
    _http("PUT", _blob_url(account, container, name), STORAGE_SCOPE, data=content, ok=(201,),
          headers={"x-ms-version": "2023-11-03", "x-ms-blob-type": "BlockBlob", "Content-Type": ctype})
    return _blob_url(account, container, name)
# @endblock


def _target():
    pub = CONFIG.get("publish") or {}
    store = CONFIG.get("history", "none")
    if store == "sharepoint" and pub.get("sharepoint"):
        return "sharepoint", pub["sharepoint"]
    if store == "blob" and pub.get("blob"):
        return "blob", pub["blob"]
    return None, None


def _history_name():
    return f"{CONFIG['tool_name']}-snapshot-"


def _history_load():
    kind, cfg = _target()
    if not kind:
        return None, "disabled"
    try:
        if kind == "sharepoint":
            site = _sp_site(cfg)
            items = [i for i in _sp_list(site, cfg.get("folder", "").rstrip("/") + "/history") if i["name"].startswith(_history_name())]
            if not items:
                return None, "empty"
            return json.loads(_sp_download(site, max(items, key=lambda i: i["name"])["id"])), "loaded"
        prefix = (cfg.get("prefix", "").strip("/") + "/history/").lstrip("/")
        blobs = [b for b in _blob_list(cfg["account"], cfg["container"], prefix + _history_name())]
        if not blobs:
            return None, "empty"
        return json.loads(_blob_get(cfg["account"], cfg["container"], max(blobs, key=lambda b: b["name"])["name"])), "loaded"
    except SourceError as exc:
        return None, "empty" if exc.code == "NOT_FOUND" else f"error: {exc.message}"


def _publish(files, snapshot_bytes, stamp):
    pub, results = CONFIG.get("publish") or {}, []
    ctypes = {".html": "text/html; charset=utf-8", ".json": "application/json", ".csv": "text/csv; charset=utf-8"}
    uploads = [(p.name, p.read_bytes()) for p in files]
    kind, _ = _target()
    for target, cfg in (("sharepoint", pub.get("sharepoint")), ("blob", pub.get("blob"))):
        if not cfg:
            continue
        items = list(uploads) + ([(f"history/{_history_name()}{stamp}.json", snapshot_bytes)] if kind == target else [])
        for name, content in items:
            ctype = ctypes.get(Path(name).suffix, "application/octet-stream")
            try:
                if target == "sharepoint":
                    url = _sp_put(_sp_site(cfg), cfg.get("folder", "").strip("/") + "/" + name, content, ctype)
                else:
                    url = _blob_put(cfg["account"], cfg["container"], (cfg.get("prefix", "").strip("/") + "/" + name).lstrip("/"), content, ctype)
                results.append({"target": target, "file": name, "status": "OK", "url": url})
            except SourceError as exc:
                results.append({"target": target, "file": name, "status": exc.code, "error": exc.message})
    return results


# ----------------------------------------------------------------------------- rules engine
def _num(value):
    try:
        return float(str(value).replace(",", ".")) if value not in (None, "") else None
    except ValueError:
        return None


def _date(value):
    if value in (None, ""):
        return None
    if isinstance(value, datetime):
        return value if value.tzinfo else value.replace(tzinfo=timezone.utc)
    text = str(value).strip().replace("Z", "+00:00")
    try:
        parsed = datetime.fromisoformat(text)
        return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)
    except ValueError:
        pass
    for fmt in ("%d/%m/%Y %H:%M:%S", "%d/%m/%Y %H:%M", "%d/%m/%Y", "%m/%d/%Y %I:%M:%S %p", "%Y%m%d"):
        try:
            return datetime.strptime(text, fmt).replace(tzinfo=timezone.utc)
        except ValueError:
            continue
    return None


def _cond(row, cond, now):
    if not cond:
        return True
    if "all" in cond:
        return all(_cond(row, c, now) for c in cond["all"])
    if "any" in cond:
        return any(_cond(row, c, now) for c in cond["any"])
    if "not" in cond:
        return not _cond(row, cond["not"], now)
    op, expected, value = cond.get("op", "eq"), cond.get("value"), row.get(cond.get("field"))
    text = "" if value is None else str(value).strip()
    if op == "empty":
        return text == ""
    if op == "not_empty":
        return text != ""
    if op in ("eq", "ne"):
        return (text.lower() == str(expected).lower()) == (op == "eq")
    if op in ("in", "not_in"):
        return (text.lower() in {str(x).lower() for x in expected}) == (op == "in")
    if op == "contains":
        return str(expected).lower() in text.lower()
    if op == "regex":
        return re.search(str(expected), text, re.IGNORECASE) is not None
    if op in ("gt", "gte", "lt", "lte"):
        number, limit = _num(value), _num(expected)
        if number is None or limit is None:
            return False
        return {"gt": number > limit, "gte": number >= limit, "lt": number < limit, "lte": number <= limit}[op]
    moment = _date(value)
    if moment is None:
        return False
    if op == "expired":
        return moment < now
    if op == "expires_within_days":
        return moment <= now + timedelta(days=float(expected))
    if op == "older_than_days":
        return moment < now - timedelta(days=float(expected))
    if op == "newer_than_days":
        return moment >= now - timedelta(days=float(expected))
    raise ValueError(f"Unknown operator '{op}'")


def _derive(data, now):
    for spec in CONFIG.get("derive", []):
        for row in data.get(spec["dataset"]) or []:
            moment = _date(row.get(spec["field"]))
            if moment is None:
                row[spec["name"]] = None
            elif spec["type"] == "days_until":
                row[spec["name"]] = (moment - now).days
            else:
                row[spec["name"]] = (now - moment).days


def _kpis(data, now):
    result = []
    for k in CONFIG.get("kpis", []):
        rows = data.get(k["dataset"])
        value = None
        if rows is not None:
            rows = [r for r in rows if _cond(r, k.get("where"), now)]
            agg, field = k.get("agg", "count"), k.get("field")
            numbers = [n for n in (_num(r.get(field)) for r in rows) if n is not None] if field else []
            if agg == "count":
                value = len(rows)
            elif agg == "distinct":
                value = len({str(r.get(field)) for r in rows if r.get(field) not in (None, "")})
            elif numbers:
                value = {"sum": sum(numbers), "avg": sum(numbers) / len(numbers), "max": max(numbers), "min": min(numbers)}[agg]
            else:
                value = 0
        result.append({"id": k["id"], "label": k.get("label", k["id"]), "value": value, "good": k.get("good"), "unit": k.get("unit", "")})
    return result


def _row_key(dataset, row):
    keys = (CONFIG.get("keys") or {}).get(dataset)
    if keys:
        return " | ".join(str(row.get(k, "")) for k in keys)
    return hashlib.sha1(json.dumps(row, sort_keys=True, default=str).encode()).hexdigest()[:12]


def _message(template, row):
    def value(match):
        found = row.get(match.group(1).strip())
        return "?" if found is None else _fmt(found)
    return re.sub(r"\{([^{}]+)\}", value, template or "")


def _findings(data, now):
    found, not_evaluated = [], []
    for rule in CONFIG.get("rules", []):
        rows = data.get(rule["dataset"])
        if rows is None:
            not_evaluated.append(rule["id"])
            continue
        for row in rows:
            if _cond(row, rule.get("when"), now):
                key = _row_key(rule["dataset"], row)
                message = _message(rule.get("message", ""), row)
                found.append({"id": f"{rule['id']}::{key}", "rule": rule["id"], "title": rule.get("title", rule["id"]),
                              "severity": rule.get("severity", "medium"), "item": key, "message": message,
                              "row": {f: row.get(f) for f in rule.get("show", [])}})
    found.sort(key=lambda f: (SEVERITIES.index(f["severity"]) if f["severity"] in SEVERITIES else 9, f["rule"], f["item"]))
    return found, not_evaluated


def _tracked_fields(dataset):
    fields = []
    for t in CONFIG.get("tables", []):
        if t["dataset"] == dataset:
            fields += t.get("columns", [])
    for r in CONFIG.get("rules", []):
        if r["dataset"] == dataset:
            fields += r.get("show", [])
    return list(dict.fromkeys(fields))[:15]


def _snapshot(data, kpis, findings, now):
    datasets = {}
    for name, rows in data.items():
        if rows is None or not (CONFIG.get("keys") or {}).get(name):
            continue
        fields = _tracked_fields(name)
        datasets[name] = {_row_key(name, r): {f: str(r.get(f, ""))[:200] for f in fields} for r in rows[:5000]}
    return {"tool": CONFIG["tool_name"], "tool_version": TOOL_VERSION, "generated_utc": _iso(now),
            "kpis": {k["id"]: k["value"] for k in kpis},
            "findings": {f["id"]: {"severity": f["severity"], "title": f["title"], "item": f["item"]} for f in findings},
            "datasets": datasets}


def _compare(current, previous, kpis):
    if not previous:
        return None
    kpi_rows = []
    for k in kpis:
        now_v, prev_v = k["value"], previous.get("kpis", {}).get(k["id"])
        delta = (now_v - prev_v) if isinstance(now_v, (int, float)) and isinstance(prev_v, (int, float)) else None
        trend = "n/a" if delta is None else "same" if delta == 0 else (
            "better" if (delta < 0) == (k.get("good") == "down") and k.get("good") else "worse" if k.get("good") else "changed")
        kpi_rows.append({"id": k["id"], "label": k["label"], "now": now_v, "previous": prev_v, "delta": delta, "trend": trend})
    cur_f, prev_f = current["findings"], previous.get("findings", {})
    diff = {"previous_utc": previous.get("generated_utc"), "kpis": kpi_rows,
            "new_findings": [dict(id=i, **cur_f[i]) for i in cur_f if i not in prev_f],
            "resolved_findings": [dict(id=i, **prev_f[i]) for i in prev_f if i not in cur_f], "datasets": {}}
    for name, rows in current["datasets"].items():
        before = previous.get("datasets", {}).get(name)
        if before is None:
            continue
        changed = []
        for key in rows.keys() & before.keys():
            delta = [{"field": f, "from": before[key].get(f), "to": v} for f, v in rows[key].items() if f in before[key] and before[key][f] != v]
            if delta:
                changed.append({"key": key, "changes": delta})
        diff["datasets"][name] = {"added": sorted(rows.keys() - before.keys())[:200], "removed": sorted(before.keys() - rows.keys())[:200],
                                  "changed": sorted(changed, key=lambda c: c["key"])[:200]}
    return diff


