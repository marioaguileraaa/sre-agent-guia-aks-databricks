# @block source:log_analytics
def source_log_analytics(src, limit, days):
    query = _render(src["query"], days) + (f"\n| take {limit}" if limit else "")
    doc = _http("POST", f"https://api.loganalytics.io/v1/workspaces/{src['workspace_id']}/query",
                "https://api.loganalytics.io/.default", json_body={"query": query, "timespan": f"P{days}D"}).json()
    meta = {"warning": doc["error"].get("message", "partial result")} if doc.get("error") else {}
    if not doc.get("tables"):
        return [], meta
    table = doc["tables"][0]
    cols = [c["name"] for c in table["columns"]]
    return _cap([dict(zip(cols, row)) for row in table["rows"]], limit), meta
# @endblock


# @block source:resource_graph
def source_resource_graph(src, limit, days):
    rows, skip = [], None
    while True:
        body = {"query": _render(src["query"], days), "options": {"$top": min(1000, limit or 1000), "resultFormat": "objectArray"}}
        if src.get("subscriptions"):
            body["subscriptions"] = src["subscriptions"]
        if skip:
            body["options"]["$skipToken"] = skip
        doc = _http("POST", ARM + "/providers/Microsoft.ResourceGraph/resources?api-version=2022-10-01", ARM_SCOPE, json_body=body).json()
        rows += _rows(doc.get("data", []), src)
        skip = doc.get("$skipToken")
        if not skip or len(rows) >= (limit or MAX_ROWS):
            return _cap(rows, limit), {}
# @endblock


