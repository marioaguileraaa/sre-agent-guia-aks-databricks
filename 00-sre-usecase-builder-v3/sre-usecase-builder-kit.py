def _client_id():
    cid = CONFIG.get("identity_client_id") or os.environ.get("AZURE_CLIENT_ID", "")
    if not cid or _is_placeholder(cid):
        raise SourceError("CONFIG_ERROR", "Set CONFIG['identity_client_id'] to the SRE Agent managed identity client ID.")
