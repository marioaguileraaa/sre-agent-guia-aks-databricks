def _token(scope):
    cached = _TOKENS.get(scope)
    if not cached or cached[1] - time.time() < 120:
        from azure.identity import ManagedIdentityCredential
        try:
            tok = ManagedIdentityCredential(client_id=_client_id()).get_token(scope)
        except Exception as exc:
            raise SourceError("AUTH_FAILED", f"Managed identity token for {scope} failed ({type(exc).__name__}).")
        _TOKENS[scope] = (tok.token, tok.expires_on)
    return _TOKENS[scope][0]


def _http(method, url, scope, *, json_body=None, data=None, headers=None, ok=(200,)):
    hdrs = {"Authorization": "Bearer " + _token(scope)}
    hdrs.update(headers or {})
    short = url.split("?")[0]
    for attempt in range(5):
        try:
            resp = requests.request(method, url, headers=hdrs, json=json_body, data=data, timeout=90,
                                    allow_redirects=(method == "GET"))
        except requests.RequestException as exc:
            if attempt == 4:
                raise SourceError("NETWORK_ERROR", f"{method} {short} failed ({type(exc).__name__}).")
            time.sleep(2 ** attempt)
            continue
        if resp.status_code in ok:
            return resp
        if resp.status_code in (429, 500, 502, 503, 504) and attempt < 4:
            try:
                wait = float(resp.headers.get("Retry-After") or 0)
            except ValueError:
                wait = 0
            time.sleep(min(wait or 2 ** attempt, 30))
            continue
        code = {401: "UNAUTHORIZED", 403: "FORBIDDEN", 404: "NOT_FOUND", 400: "BAD_REQUEST"}.get(resp.status_code, "HTTP_ERROR")
        raise SourceError(code, f"{method} {short} -> HTTP {resp.status_code}: {resp.text[:300]}", resp.status_code)
    raise SourceError("HTTP_ERROR", f"{method} {short} exhausted retries.")


def _flat(obj, prefix="", out=None, depth=0):
    out = {} if out is None else out
    for key, value in (obj or {}).items():
        name = f"{prefix}{key}"
        if isinstance(value, dict) and depth < 2:
            _flat(value, name + ".", out, depth + 1)
        elif isinstance(value, (list, dict)):
            out[name] = json.dumps(value, ensure_ascii=False, default=str)[:2000]
        else:
            out[name] = value
    return out


def _rows(items, src):
    field, out = src.get("explode"), []
    for item in items:
        if not field:
            out.append(_flat(item))
            continue
        children = item.get(field) or []
        if isinstance(children, str):
            try:
                children = json.loads(children)
            except ValueError:
                children = []
        base = _flat({k: v for k, v in item.items() if k != field})
        for child in children:
            out.append(dict(base, **_flat(child if isinstance(child, dict) else {"value": child}, field + ".")))
    return out


def _cap(rows, limit):
    return rows[: (limit or MAX_ROWS)]


# ----------------------------------------------------------------------------- file parsing
def _parse_file(name, content, src):
    low = name.lower()
    if low.endswith((".xlsx", ".xlsm")):
        from openpyxl import load_workbook
        book = load_workbook(io.BytesIO(content), read_only=True, data_only=True)
        sheets = [src["sheet"]] if src.get("sheet") else (book.sheetnames if src.get("all_sheets") else book.sheetnames[:1])
        rows, header_row = [], int(src.get("header_row", 1))
        for sheet in sheets:
            if sheet not in book.sheetnames:
                raise SourceError("NOT_FOUND", f"Sheet '{sheet}' not found in {name}. Sheets: {book.sheetnames}")
            header = None
            for index, values in enumerate(book[sheet].iter_rows(values_only=True), start=1):
                if index < header_row:
                    continue
                if header is None:
                    header, seen = [], {}
                    for col, value in enumerate(values):
                        label = str(value).strip() if value not in (None, "") else f"col{col + 1}"
                        seen[label] = seen.get(label, 0) + 1
                        header.append(label if seen[label] == 1 else f"{label}_{seen[label]}")
                    continue
                if all(value is None or str(value).strip() == "" for value in values):
                    continue
                row = {header[i]: (v.isoformat() if hasattr(v, "isoformat") else v)
                       for i, v in enumerate(values) if i < len(header)}
                if len(sheets) > 1:
                    row["_sheet"] = sheet
                rows.append(row)
                if len(rows) >= MAX_ROWS:
                    break
        book.close()
        return rows
    if low.endswith(".csv"):
        text = content.decode("utf-8-sig", errors="replace")
        first = text.split("\n", 1)[0]
        delimiter = src.get("delimiter") or (";" if first.count(";") > first.count(",") else ",")
        return list(csv.DictReader(io.StringIO(text), delimiter=delimiter))[:MAX_ROWS]
    if low.endswith(".json"):
        doc = json.loads(content)
        items = doc if isinstance(doc, list) else doc.get(src.get("json_path") or "value", [])
        return [_flat(x) if isinstance(x, dict) else {"value": x} for x in items][:MAX_ROWS]
    raise SourceError("UNSUPPORTED_FILE", f"{name}: supported formats are .xlsx, .xlsm, .csv and .json.")


