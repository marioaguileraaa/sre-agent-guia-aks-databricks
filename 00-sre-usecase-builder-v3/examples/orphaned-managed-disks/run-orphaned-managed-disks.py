# Azure SRE Agent hands only ~4,000 characters of a tool result to the model: keep the answer inside that budget
# and save the complete result as a JSON file linked from the answer.
RESULT_BUDGET = 3800


def _link(name):
    match = re.search(r"/tmp/ThreadFiles/([0-9a-fA-F-]{36})", Path.cwd().as_posix())
    folder = Path.cwd() / CONFIG["tool_name"]
    return f"/api/files/tmp/ThreadFiles/{match.group(1)}/{quote(CONFIG['tool_name'])}/{quote(name)}" if match else str(folder / name)


def _size(value):
    return len(json.dumps(value, ensure_ascii=False, default=str))


def _shrink_once(node):
    best = None

    def walk(parent, key, value):
        nonlocal best
        if isinstance(value, dict):
            if parent is not None and len([k for k in value if k != "_more_keys"]) > 1:
                size = _size(value)
                if not best or size > best[0]:
                    best = (size, parent, key, "dict")
            for k, v in value.items():
                if k != "result_truncated":
                    walk(value, k, v)
        elif isinstance(value, list):
            if len(value) > 1:
                size = _size(value)
                if not best or size > best[0]:
                    best = (size, parent, key, "list")
            for i, v in enumerate(value):
                walk(value, i, v)
        elif isinstance(value, str) and len(value) > 160 and (not best or len(value) > best[0]):
            best = (len(value), parent, key, "str")

    walk(None, None, node)
    if not best:
        return False
    _, parent, key, kind = best
    value = parent[key]
    if kind == "dict":
        real = [k for k in value if k != "_more_keys"]
        keep = real[:max(1, len(real) // 2)]
        parent[key] = dict({k: value[k] for k in keep}, _more_keys=value.get("_more_keys", 0) + len(real) - len(keep))
        return True
    parent[key] = value[:max(1, len(value) // 2)] if kind == "list" else value[:max(120, len(value) // 2)] + "..."
    return True


def _fit(result, mode):
    if _size(result) <= RESULT_BUDGET:
        return result
    link = None
    try:
        folder = Path.cwd() / CONFIG["tool_name"]
        folder.mkdir(parents=True, exist_ok=True)
        name = f"{mode}-result-{_now().strftime('%Y%m%dT%H%M%S%fZ')}.json"
        (folder / name).write_text(json.dumps(result, ensure_ascii=False, indent=1, default=str), encoding="utf-8")
        link = _link(name)
    except OSError:
        pass
    out = json.loads(json.dumps(result, ensure_ascii=False, default=str))
    if mode == "discover":
        for s in out.get("sources", []):
            s["sample_rows"] = s.get("sample_rows", [])[:1]
        if _size(out) > RESULT_BUDGET:
            for s in out.get("sources", []):
                s["columns"] = [c["name"] if isinstance(c, dict) else c for c in s.get("columns", [])]
        if _size(out) > RESULT_BUDGET:
            for s in out.get("sources", []):
                s.pop("sample_rows", None)
    out = dict({"result_truncated": {"full_result": link, "note": "Lists were shortened to fit the agent; open full_result or the report files for everything."}}, **out)
    for _ in range(400):
        if _size(out) <= RESULT_BUDGET or not _shrink_once(out):
            break
    if _size(out) > RESULT_BUDGET:
        out = {k: out[k] for k in ("result_truncated", "status", "error_code", "message", "next") if k in out}
        out["omitted_keys"] = [k for k in result if k not in out]
    return out


def _run_tool(mode="report", publish="no", lookback_days=0):
    started, now = time.time(), _now()
    mode, publish = (mode or "report").strip().lower(), (publish or "no").strip().lower()
    if mode not in ("report", "discover", "self_test"):
        return {"status": "FAILED", "error_code": "BAD_PARAMETER", "message": "mode must be report, discover or self_test"}
    if publish not in ("yes", "no"):
        return {"status": "FAILED", "error_code": "BAD_PARAMETER", "message": "publish must be yes or no"}
    days = int(lookback_days) if lookback_days and int(lookback_days) > 0 else int(CONFIG.get("lookback_days", 7))
    if not 1 <= days <= 366:
        return {"status": "FAILED", "error_code": "BAD_PARAMETER", "message": "lookback_days must be between 1 and 366"}
    simulated = mode == "self_test"
    data, sources = {}, []
    for src in CONFIG["sources"]:
        info = {"id": src["id"], "type": src["type"]}
        try:
            if simulated:
                rows, meta = _selftest_collect(src, now)
            else:
                pending = [k for k, v in src.items() if _is_placeholder(v)]
                if pending:
                    raise SourceError("CONFIG_ERROR", f"Fill CONFIG placeholders for source '{src['id']}': {', '.join(pending)}")
                fn = globals().get("source_" + src["type"])
                if fn is None:
                    raise SourceError("CONFIG_ERROR", f"Source type '{src['type']}' is not included in this tool.")
                rows, meta = fn(src, 25 if mode == "discover" else int(src.get("max_rows", 0)), days)
            data[src["id"]] = rows
            info.update(meta, status="OK", rows=len(rows))
        except SourceError as exc:
            data[src["id"]] = None
            info.update(status=exc.code, error=exc.message, http_status=exc.http_status)
        sources.append(info)
    if mode == "discover":
        out = []
        for s in sources:
            rows = data.get(s["id"]) or []
            cols = list(dict.fromkeys(k for r in rows for k in r))
            out.append(dict(s, columns=[{"name": c, "example": str(next((r[c] for r in rows if r.get(c) not in (None, "")), ""))[:80]} for c in cols],
                            sample_rows=[{k: str(v)[:80] for k, v in r.items()} for r in rows[:5]]))
        history, history_state = _history_load()
        return {"status": "OK" if all(s["status"] == "OK" for s in sources) else "PARTIAL", "mode": "discover",
                "sources": out, "history_store": history_state, "previous_report_utc": (history or {}).get("generated_utc"),
                "elapsed_s": round(time.time() - started, 1)}
    ok_sources = [s for s in sources if s["status"] == "OK"]
    status = "SIMULATED" if simulated else "OK" if len(ok_sources) == len(sources) else "PARTIAL" if ok_sources else "FAILED"
    if status == "FAILED":
        return {"status": "FAILED", "mode": mode, "sources": sources, "message": "No source could be read. See sources[].error."}
    _derive(data, now)
    kpis = _kpis(data, now)
    findings, not_evaluated = _findings(data, now)
    snapshot = _snapshot(data, kpis, findings, now)
    previous, history_state = (_selftest_previous(data, now), "simulated") if simulated else _history_load()
    diff = _compare(snapshot, previous, kpis)
    summary = {"status": status, "mode": mode, "title": CONFIG["title"], "generated_utc": _iso(now), "lookback_days": days,
               "findings_by_severity": {s: sum(1 for f in findings if f["severity"] == s) for s in SEVERITIES},
               "kpis": [{k: v for k, v in x.items() if k in ("id", "label", "value")} for x in kpis],
               "history": history_state, "previous_report_utc": (diff or {}).get("previous_utc"),
               "new_findings": len(diff["new_findings"]) if diff else None, "resolved_findings": len(diff["resolved_findings"]) if diff else None}
    ctx = {"now": now, "days": days, "simulated": simulated, "status": status, "data": data, "sources": sources,
           "kpis": kpis, "findings": findings, "not_evaluated": not_evaluated, "diff": diff, "summary": summary}
    files, links, stamp = _write_outputs(ctx, snapshot)
    published = []
    if publish == "yes" and not simulated:
        published = _publish(files[:3], json.dumps(snapshot, ensure_ascii=False, default=str).encode(), stamp)
    return dict(summary, sources=sources, top_findings=[{k: f[k] for k in ("severity", "title", "item", "message")} for f in findings[:15]],
                comparison=None if not diff else {"kpis": diff["kpis"], "new": diff["new_findings"][:10], "resolved": diff["resolved_findings"][:10],
                                                  "datasets": {n: {k: len(v) for k, v in d.items()} for n, d in diff["datasets"].items()}},
                files=links, published=published, elapsed_s=round(time.time() - started, 1))
