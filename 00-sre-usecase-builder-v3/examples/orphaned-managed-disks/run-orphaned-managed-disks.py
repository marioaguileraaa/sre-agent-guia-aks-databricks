def _num(value):
    try:
        return float(str(value).replace(",", ".")) if value not in (None, "") else None
    except ValueError:
        return None


def _date(value):
    if value in (None, ""):
        return None
    if isinstance(value, datetime):
        return value if value.tzinfo else value.replace(tzinfo=timezone.utc)
    text = str(value).strip().replace("Z", "+00:00")
    try:
        parsed = datetime.fromisoformat(text)
        return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)
    except ValueError:
        pass
    for fmt in ("%d/%m/%Y %H:%M:%S", "%d/%m/%Y %H:%M", "%d/%m/%Y", "%m/%d/%Y %I:%M:%S %p", "%Y%m%d"):
        try:
            return datetime.strptime(text, fmt).replace(tzinfo=timezone.utc)
        except ValueError:
            continue
    return None


def _cond(row, cond, now):
    if not cond:
        return True
    if "all" in cond:
        return all(_cond(row, c, now) for c in cond["all"])
    if "any" in cond:
        return any(_cond(row, c, now) for c in cond["any"])
    if "not" in cond:
        return not _cond(row, cond["not"], now)
    op, expected, value = cond.get("op", "eq"), cond.get("value"), row.get(cond.get("field"))
    text = "" if value is None else str(value).strip()
    if op == "empty":
        return text == ""
    if op == "not_empty":
        return text != ""
    if op in ("eq", "ne"):
        return (text.lower() == str(expected).lower()) == (op == "eq")
    if op in ("in", "not_in"):
        return (text.lower() in {str(x).lower() for x in expected}) == (op == "in")
    if op == "contains":
        return str(expected).lower() in text.lower()
    if op == "regex":
        return re.search(str(expected), text, re.IGNORECASE) is not None
    if op in ("gt", "gte", "lt", "lte"):
        number, limit = _num(value), _num(expected)
        if number is None or limit is None:
            return False
        return {"gt": number > limit, "gte": number >= limit, "lt": number < limit, "lte": number <= limit}[op]
    moment = _date(value)
    if moment is None:
        return False
    if op == "expired":
        return moment < now
    if op == "expires_within_days":
        return moment <= now + timedelta(days=float(expected))
    if op == "older_than_days":
        return moment < now - timedelta(days=float(expected))
    if op == "newer_than_days":
        return moment >= now - timedelta(days=float(expected))
    raise ValueError(f"Unknown operator '{op}'")


def _derive(data, now):
    for spec in CONFIG.get("derive", []):
        for row in data.get(spec["dataset"]) or []:
            moment = _date(row.get(spec["field"]))
            if moment is None:
                row[spec["name"]] = None
            elif spec["type"] == "days_until":
                row[spec["name"]] = (moment - now).days
            else:
                row[spec["name"]] = (now - moment).days


def _kpis(data, now):
    result = []
    for k in CONFIG.get("kpis", []):
        rows = data.get(k["dataset"])
        value = None
        if rows is not None:
            rows = [r for r in rows if _cond(r, k.get("where"), now)]
            agg, field = k.get("agg", "count"), k.get("field")
            numbers = [n for n in (_num(r.get(field)) for r in rows) if n is not None] if field else []
            if agg == "count":
                value = len(rows)
            elif agg == "distinct":
                value = len({str(r.get(field)) for r in rows if r.get(field) not in (None, "")})
            elif numbers:
                value = {"sum": sum(numbers), "avg": sum(numbers) / len(numbers), "max": max(numbers), "min": min(numbers)}[agg]
            else:
                value = 0
        result.append({"id": k["id"], "label": k.get("label", k["id"]), "value": value, "good": k.get("good"), "unit": k.get("unit", "")})
    return result


def _row_key(dataset, row):
    keys = (CONFIG.get("keys") or {}).get(dataset)
    if keys:
        return " | ".join(str(row.get(k, "")) for k in keys)
    return hashlib.sha1(json.dumps(row, sort_keys=True, default=str).encode()).hexdigest()[:12]


def _message(template, row):
    def value(match):
        found = row.get(match.group(1).strip())
        return "?" if found is None else _fmt(found)
    return re.sub(r"\{([^{}]+)\}", value, template or "")


def _findings(data, now):
    found, not_evaluated = [], []
    for rule in CONFIG.get("rules", []):
        rows = data.get(rule["dataset"])
        if rows is None:
            not_evaluated.append(rule["id"])
            continue
        for row in rows:
            if _cond(row, rule.get("when"), now):
                key = _row_key(rule["dataset"], row)
                message = _message(rule.get("message", ""), row)
                found.append({"id": f"{rule['id']}::{key}", "rule": rule["id"], "title": rule.get("title", rule["id"]),
                              "severity": rule.get("severity", "medium"), "item": key, "message": message,
                              "row": {f: row.get(f) for f in rule.get("show", [])}})
    found.sort(key=lambda f: (SEVERITIES.index(f["severity"]) if f["severity"] in SEVERITIES else 9, f["rule"], f["item"]))
    return found, not_evaluated


