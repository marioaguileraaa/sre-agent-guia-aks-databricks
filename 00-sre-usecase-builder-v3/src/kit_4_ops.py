def _jwt_claims(token):
    try:
        part = token.split(".")[1]
        return json.loads(base64.urlsafe_b64decode(part + "=" * (-len(part) % 4)))
    except Exception:
        return {}


def _environment():
    import requests
    from azure.identity import ManagedIdentityCredential
    out = {"identity": {}, "errors": []}
    client_id = os.environ.get("AZURE_CLIENT_ID", "")
    if not client_id:
        return {"status": "NO_IDENTITY", "message": "AZURE_CLIENT_ID is not set: run this inside the Azure SRE Agent."}
    cred = ManagedIdentityCredential(client_id=client_id)

    def get(url, scope="https://management.azure.com/.default", method="GET", body=None):
        tok = cred.get_token(scope).token
        resp = requests.request(method, url, headers={"Authorization": "Bearer " + tok}, json=body, timeout=60)
        if resp.status_code >= 400:
            raise RuntimeError(f"HTTP {resp.status_code} {url.split('?')[0]}: {resp.text[:200]}")
        return resp.json()

    try:
        claims = _jwt_claims(cred.get_token("https://management.azure.com/.default").token)
        out["identity"] = {"client_id": client_id, "principal_id": claims.get("oid"), "tenant_id": claims.get("tid")}
    except Exception as exc:
        return {"status": "AUTH_FAILED", "message": f"{type(exc).__name__}: {str(exc)[:300]}"}
    subs = []
    try:
        subs = [{"id": s["subscriptionId"], "name": s.get("displayName")} for s in get(ARM + "/subscriptions?api-version=2022-12-01").get("value", [])]
    except Exception as exc:
        out["errors"].append(f"subscriptions: {exc}")
    out["subscriptions"] = subs

    def arg(query):
        body = {"subscriptions": [s["id"] for s in subs][:1000], "query": query, "options": {"$top": 1000}}
        return get(ARM + "/providers/Microsoft.ResourceGraph/resources?api-version=2022-10-01", method="POST", body=body).get("data", [])

    if subs:
        queries = {
            "log_analytics_workspaces": "resources | where type =~ 'microsoft.operationalinsights/workspaces' | project name, resourceGroup, subscriptionId, location, customerId = tostring(properties.customerId), id",
            "storage_accounts": "resources | where type =~ 'microsoft.storage/storageaccounts' | project name, resourceGroup, subscriptionId, id",
            "kusto_clusters": "resources | where type =~ 'microsoft.kusto/clusters' | project name, resourceGroup, uri = tostring(properties.uri), id",
            "top_resource_types": "resources | summarize count_ = count() by type | top 25 by count_",
        }
        for key, query in queries.items():
            try:
                out[key] = arg(query)
            except Exception as exc:
                out["errors"].append(f"{key}: {exc}")
    roles, names = [], {}
    for sub in subs[:25]:
        try:
            url = f"{ARM}/subscriptions/{sub['id']}/providers/Microsoft.Authorization/roleAssignments?api-version=2022-04-01&$filter=assignedTo('{out['identity']['principal_id']}')"
            for ra in get(url).get("value", []):
                rd = ra["properties"]["roleDefinitionId"]
                if rd not in names:
                    try:
                        names[rd] = get(ARM + rd + "?api-version=2022-04-01")["properties"]["roleName"]
                    except Exception:
                        names[rd] = rd.split("/")[-1]
                roles.append({"role": names[rd], "scope": ra["properties"]["scope"]})
        except Exception as exc:
            out["errors"].append(f"role assignments {sub['id']}: {str(exc)[:160]}")
    out["azure_roles"] = list({(r["role"], r["scope"]): r for r in roles}.values())
    try:
        out["graph_app_roles"] = sorted(_jwt_claims(cred.get_token("https://graph.microsoft.com/.default").token).get("roles", []))
    except Exception as exc:
        out["graph_app_roles"] = []
        out["errors"].append(f"graph token: {type(exc).__name__}")
    out["status"] = "OK" if not out["errors"] else "PARTIAL"
    out["hint"] = ("Use log_analytics_workspaces[].customerId as workspace_id. azure_roles and graph_app_roles are what the agent can already read; "
                   "scaffold marks those permissions as ALREADY_GRANTED.")
    return out


