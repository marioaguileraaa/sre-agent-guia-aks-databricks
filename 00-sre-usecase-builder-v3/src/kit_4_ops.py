def _get(ref):
    parts = [p for p in (ref or "").strip().strip('"').split("/") if p]
    if len(parts) < 2:
        return {"status": "INVALID", "message": "spec_json must be '<use-case name>/<part>[/<page>]'", "parts": GET_PARTS}
    name, part = parts[0], parts[1].lower()
    page = int(parts[2]) if len(parts) > 2 and parts[2].isdigit() else 1
    folder = Path.cwd() / "sre-usecase-builder" / name
    path = folder / f"{name}-scaffold.json"
    if not path.exists():
        return {"status": "NOT_FOUND", "message": f"No scaffold for '{name}' in this thread. Run scaffold first."}
    full = json.loads(path.read_text(encoding="utf-8"))
    b = full["blocks"]
    texts = {
        "answer": lambda: _answer_md(full),
        "tool": lambda: json.dumps({k: v for k, v in b["python_tool"].items() if k != "config_section"}, ensure_ascii=False, indent=1),
        "config": lambda: b["python_tool"]["config_section"],
        "skill": lambda: b["skill"]["skill_md"],
        "subagent": lambda: json.dumps({k: v for k, v in b["subagent"].items() if k != "instructions"}, ensure_ascii=False) + "\n\n" + b["subagent"]["instructions"],
        "task": lambda: json.dumps(b["scheduled_task"], ensure_ascii=False, indent=1),
        "permissions": lambda: json.dumps(full["permissions"], ensure_ascii=False, indent=1),
        "tests": lambda: "\n".join(full["test_prompts"]),
        "setup": lambda: (folder / f"{name}-SETUP.md").read_text(encoding="utf-8"),
        "code": lambda: (folder / f"{full['names']['tool']}.py").read_text(encoding="utf-8"),
        "spec": lambda: (folder / f"{name}-spec.json").read_text(encoding="utf-8"),
    }
    if part not in texts:
        return {"status": "INVALID", "message": f"Unknown part '{part}'", "parts": GET_PARTS}
    chunk, page, pages = _page(texts[part](), page)
    return {"status": "OK", "part": f"{name}/{part}", "page": page, "pages": pages,
            "next": f"call get with spec_json='{name}/{part}/{page + 1}'" if page < pages else "complete", "content": chunk}


def _kit_main(operation="catalog", spec_json="", code=""):
    op = (operation or "catalog").strip().lower()
    try:
        if op == "catalog":
            return _fit(_catalog_detail(spec_json) if (spec_json or "").strip() else _catalog_index(), "catalog")
        if op == "environment":
            return _env_summary(_env_cached())
        if op == "lint":
            return _fit(_lint(code or ""), "lint")
        if op == "get":
            return _get(spec_json)
        if op in ("probe", "scaffold"):
            spec, error = _parse_spec(spec_json)
            if error:
                return error
            return _fit(_probe(spec) if op == "probe" else _scaffold(spec), op)
        return {"status": "INVALID", "message": "operation must be catalog, environment, probe, scaffold, get or lint"}
    except Exception as exc:
        return {"status": "KIT_ERROR", "error": f"{type(exc).__name__}: {exc}", "trace": traceback.format_exc()[-1500:],
                "next": "Report this error; retry scaffold once with a simpler spec."}
