def _parse_spec(spec_json):
    if isinstance(spec_json, dict):
        return spec_json, None
    text = (spec_json or "").strip()
    fence = re.search(r"```(?:json)?\s*(\{.*\})\s*```", text, re.S)
    if fence:
        text = fence.group(1)
    if not text:
        return None, {"status": "INVALID", "errors": [{"path": "spec_json", "error": "empty", "fix": "call operation=catalog and start from a recipe"}]}
    try:
        return json.loads(text), None
    except json.JSONDecodeError as exc:
        return None, {"status": "INVALID", "errors": [{"path": "spec_json", "error": f"not valid JSON: {exc.msg} at line {exc.lineno} col {exc.colno}",
                                                       "fix": "send strict JSON (double quotes, no comments, no trailing commas)"}]}


def _auto_keys(config, discover):
    picked = {}
    preferred = ["id", "resourceId", "_ResourceId", "ResourceId", "Computer", "appId", "userPrincipalName", "name", "displayName"]
    for s in (discover or {}).get("sources", []):
        if s["id"] in config["keys"] or s.get("status") != "OK":
            continue
        cols = [c["name"] for c in s.get("columns", [])]
        for p in preferred:
            if p in cols:
                picked[s["id"]] = [p]
                break
    return picked


def _probe(spec):
    config, meta, errors, warnings = _validate(spec)
    if errors:
        return {"status": "INVALID", "errors": errors, "warnings": warnings}
    pending = _walk_placeholders(config["sources"])
    if pending:
        return {"status": "NEEDS_INPUT", "pending_inputs": pending, "message": "Fill the placeholders in sources (operation environment lists workspaces, storage, subscriptions)."}
    if not _live_possible():
        return {"status": "NO_IDENTITY", "message": "probe must run inside Azure SRE Agent (managed identity not available)."}
    code = _build_code(config, meta)
    _, discover, elapsed = _run(code, "discover")
    env = _env_cached()
    perms = _permissions(config, env if env.get("status") in ("OK", "PARTIAL") else None)
    failing = [s for s in discover.get("sources", []) if s.get("status") != "OK"]
    return {"status": discover.get("status"), "elapsed_s": elapsed, "sources": discover.get("sources"), "field_check": _field_check(config, discover),
            "suggested_keys": _auto_keys(config, discover),
            "permission_fixes": [p for p in perms if p["status"] == "TO_GRANT"] if any(s.get("status") in ("FORBIDDEN", "UNAUTHORIZED") for s in failing) else [],
            "warnings": warnings, "error": discover.get("error"), "trace": discover.get("trace")}


def _scaffold(spec):
    config, meta, errors, warnings = _validate(spec)
    if errors:
        return {"status": "INVALID", "errors": errors, "warnings": warnings,
                "next": "Fix every error (path + fix) and call scaffold again with the corrected spec."}
    pending = _walk_placeholders({"sources": config["sources"], "publish": config.get("publish")})
    env = _env_cached() if _live_possible() else None
    env_ok = bool(env and env.get("status") in ("OK", "PARTIAL"))
    verification, live = {}, None
    if not pending and _live_possible():
        code0 = _build_code(config, meta)
        _, live, live_s = _run(code0, "discover")
        if not config["keys"]:
            config["keys"] = _auto_keys(config, live)
            if config["keys"]:
                warnings.append(f"keys were not given: picked {config['keys']} from live columns.")
        verification["live_discover"] = f"{live.get('status')} in {live_s}s - " + "; ".join(
            f"{s['id']}: {s.get('status')}" + (f" ({s.get('rows', 0)} rows, {len(s.get('columns', []))} columns)" if s.get("status") == "OK" else f" - {str(s.get('error'))[:160]}")
            for s in live.get("sources", [])) if live.get("sources") else f"{live.get('status')}: {live.get('error') or live.get('message')}"
    elif pending:
        verification["live_discover"] = "NOT RUN - placeholders to fill: " + ", ".join(p["path"] for p in pending)
    else:
        verification["live_discover"] = "NOT RUN - no managed identity here (run self_test + discover in Builder)"
    code = _build_code(config, meta)
    lint = _lint(code)
    verification["lint"] = lint["status"] + (": " + "; ".join(lint["errors"]) if lint["errors"] else "")
    if lint["status"] != "PASS":
        return {"status": "FAILED", "stage": "lint", "lint": lint, "verification": verification}
    ns, selftest, st_s = _run(code, "self_test")
    if selftest.get("status") != "SIMULATED":
        return {"status": "FAILED", "stage": "self_test", "self_test": selftest, "verification": verification,
                "next": "Usually a condition/field mismatch: check the error, fix the spec and scaffold again."}
    fired, silent = _rule_coverage(ns, config)
    verification["self_test"] = (f"SIMULATED OK in {st_s}s - network blocked, {len(fired)}/{len(config['rules'])} rules fired on synthetic data, "
                                 f"{len(selftest.get('kpis', []))} KPIs, comparison with a simulated previous run, HTML/CSV/JSON written")
    if silent:
        warnings.append("Rules that never fired on synthetic data (check the condition, or add sample_rows to the source): " + ", ".join(silent))
    field_check = _field_check(config, live) if live else []
    for fc in field_check:
        if fc["status"] == "MISSING_FIELDS":
            warnings.append(f"Live columns of '{fc['dataset']}' do not include: " + ", ".join(
                m["field"] + (f" (did you mean {m['did_you_mean']})" if m["did_you_mean"] else "") for m in fc["missing"]))
    if field_check:
        verification["field_check"] = "; ".join(f"{fc['dataset']}: {fc['status']}" for fc in field_check)
    perms = _permissions(config, env if env_ok else None)
    folder = Path.cwd() / "sre-usecase-builder" / meta["name"]
    folder.mkdir(parents=True, exist_ok=True)
    code_name = f"{meta['tool']}.py"
    docs = {code_name: code, f"{meta['name']}-BUILDER-BLOCKS.md": _blocks_md(config, meta, code, lint),
            f"{meta['name']}-SETUP.md": _setup_md(config, meta, perms, verification, code_name),
            f"{meta['name']}-spec.json": json.dumps(spec, ensure_ascii=False, indent=2)}
    for fname, content in docs.items():
        (folder / fname).write_text(content, encoding="utf-8")
    match = re.search(r"/tmp/ThreadFiles/([0-9a-fA-F-]{36})", Path.cwd().as_posix())
    link = (lambda f: f"/api/files/tmp/ThreadFiles/{match.group(1)}/sre-usecase-builder/{meta['name']}/{quote(f)}") if match else (lambda f: str(folder / f))
    live_ok = bool(live and live.get("status") == "OK" and all(fc["status"] in ("OK", "NO_ROWS") for fc in field_check))
    status = "READY_WITH_INPUTS" if pending else "READY_LIVE_VERIFIED" if live_ok else "READY_LIVE_ISSUES" if live else "READY"
    config_text = code[code.index("CONFIG = "): code.index("\n\n", code.index("CONFIG = "))]
    full = {
        "status": status,
        "meaning": {"READY_LIVE_VERIFIED": "lint + self_test passed and live data was read with the expected fields",
                    "READY_LIVE_ISSUES": "code is correct; live read failed or fields differ - see verification/permissions/warnings",
                    "READY_WITH_INPUTS": "code is correct; fill pending_inputs in CONFIG before the live run",
                    "READY": "lint + self_test passed; live check must be done in Builder (discover)"}[status],
        "names": {k: meta[k] for k in ("tool", "skill", "agent", "task", "cron")},
        "verification": verification, "pending_inputs": pending, "permissions": perms, "warnings": warnings,
        "self_test_report": selftest.get("files"), "self_test_kpis": selftest.get("kpis"),
        "files": {f: link(f) for f in docs},
        "blocks": {
            "python_tool": {"name": meta["tool"], "description": _tool_description(config, meta), "timeout_seconds": 300,
                            "parameters": TOOL_PARAMS, "code_file": link(code_name), "code_bytes": len(code.encode()),
                            "code_sha256": hashlib.sha256(code.encode()).hexdigest()[:16], "config_section": config_text[:6000]},
            "skill": {"name": meta["skill"], "tools": [meta["tool"]], "skill_md": _skill_md(config, meta)},
            "subagent": {"name": meta["agent"], "description": (meta["description"] or config["title"])[:300], "tools": [meta["tool"]],
                         "skills": [meta["skill"]], "instructions": _instructions(config, meta)},
            "scheduled_task": {"name": meta["task"], "agent": meta["agent"], "cron_utc": meta["cron"], "prompt": _task_prompt(config, meta)},
        },
        "test_prompts": _test_prompts(config, meta),
    }
