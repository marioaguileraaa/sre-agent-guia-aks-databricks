def _fit(result, label):
    if _size(result) <= RESULT_BUDGET:
        return result
    link = None
    try:
        folder = Path.cwd() / "sre-usecase-builder" / "_results"
        folder.mkdir(parents=True, exist_ok=True)
        path = folder / f"{re.sub(r'[^a-zA-Z0-9_-]', '_', label)}-{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')}.json"
        path.write_text(json.dumps(result, ensure_ascii=False, indent=1, default=str), encoding="utf-8")
        link = _thread_link(path)
    except OSError:
        pass
    out = dict({"result_truncated": {"full_result": link, "note": "Shortened to fit the agent; the full result is in full_result."}},
               **json.loads(json.dumps(result, ensure_ascii=False, default=str)))
    for _ in range(400):
        if _size(out) <= RESULT_BUDGET or not _shrink_once(out):
            break
    if _size(out) > RESULT_BUDGET:
        out = {k: out[k] for k in ("result_truncated", "status", "error_code", "message", "next") if k in out}
        out["omitted_keys"] = [k for k in result if k not in out]
    return out


def _env_summary(env):
    if env.get("status") not in ("OK", "PARTIAL"):
        return env
    short = lambda scope: re.sub(r"^/subscriptions/([0-9a-f]{8})[0-9a-f-]+", r"sub \1..", scope or "")
    out = {"status": env["status"], "identity": env.get("identity"),
           "subscriptions": env.get("subscriptions", [])[:10],
           "log_analytics_workspaces": [{"name": w.get("name"), "customerId": w.get("customerId"), "resourceGroup": w.get("resourceGroup")}
                                        for w in env.get("log_analytics_workspaces", [])][:12],
           "storage_accounts": [s.get("name") for s in env.get("storage_accounts", [])][:12],
           "kusto_clusters": [{"name": k.get("name"), "uri": k.get("uri")} for k in env.get("kusto_clusters", [])][:5],
           "azure_roles": sorted({f"{r['role']} @ {short(r['scope'])}" for r in env.get("azure_roles", [])})[:15],
           "graph_app_roles": env.get("graph_app_roles", []),
           "errors": env.get("errors", [])[:3],
           "hint": env.get("hint")}
    return _fit(out, "environment")


def _page(text, page):
    pages = max(1, -(-len(text) // PAGE_CHARS))
    page = min(max(1, page), pages)
    chunk = text[(page - 1) * PAGE_CHARS: page * PAGE_CHARS]
    return chunk, page, pages


