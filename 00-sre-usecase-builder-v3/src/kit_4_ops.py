# ----------------------------------------------------------------------------- run generated code
class _NoNetwork:
    class RequestException(Exception):
        pass

    def __getattr__(self, name):
        def blocked(*args, **kwargs):
            raise RuntimeError("network blocked during self_test")
        return blocked


def _load(code, offline):
    ns = {"__name__": "generated_tool"}
    with contextlib.redirect_stdout(io.StringIO()):
        exec(compile(code, "generated_tool.py", "exec"), ns)  # noqa: S102 - kit runs only code it generated itself
    if offline:
        ns["requests"] = _NoNetwork()
    return ns


def _run(code, mode):
    started = time.time()
    try:
        ns = _load(code, offline=(mode == "self_test"))
        with contextlib.redirect_stdout(io.StringIO()):
            result = ns.get("_run_tool", ns["main"])(mode=mode, publish="no")
        return ns, result, round(time.time() - started, 1)
    except Exception as exc:
        return None, {"status": "CRASH", "error": f"{type(exc).__name__}: {exc}", "trace": traceback.format_exc()[-1500:]}, round(time.time() - started, 1)


def _rule_coverage(ns, config):
    now = ns["_now"]()
    data = {s["id"]: ns["_selftest_collect"](s, now)[0] for s in config["sources"]}
    ns["_derive"](data, now)
    findings, _ = ns["_findings"](data, now)
    fired = sorted({f["rule"] for f in findings})
    return fired, [r["id"] for r in config["rules"] if r["id"] not in fired]


def _field_check(config, discover):
    by_source = {s["id"]: s for s in (discover or {}).get("sources", [])}
    derived = {(d["dataset"], d["name"]) for d in config.get("derive", [])}
    report = []
    for dataset, fields in _referenced_fields(config).items():
        live = by_source.get(dataset) or {}
        if live.get("status") != "OK":
            report.append({"dataset": dataset, "status": "NOT_CHECKED", "reason": live.get("error") or "source not read"})
            continue
        cols = [c["name"] for c in live.get("columns", [])]
        if not cols:
            report.append({"dataset": dataset, "status": "NO_ROWS", "reason": "source returned 0 rows in discover; fields cannot be verified"})
            continue
        missing = []
        for field, used in fields.items():
            if field not in cols and (dataset, field) not in derived:
                missing.append({"field": field, "used_by": used, "did_you_mean": difflib.get_close_matches(field, cols, n=3, cutoff=0.5)})
        report.append({"dataset": dataset, "status": "OK" if not missing else "MISSING_FIELDS", "missing": missing, "live_columns": cols[:60]})
    return report


